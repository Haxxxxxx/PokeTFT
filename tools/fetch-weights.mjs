/**
 * Bakes each species' canonical weight into src/game/data/mon-weights.ts.
 *
 * Companion to fetch-heights.mjs, and it exists because HEIGHT alone is a poor
 * proxy for how much space a Pokemon appears to take up. PokeAPI measures a
 * serpentine species along its LENGTH: Ekans is "2.0 m" of snake, and a coiled
 * snake does not look twice the size of a 0.3 m bird. Scaling by height alone
 * made exactly that mistake, which is what "Ekans is too big" was.
 *
 * Mass is the better signal for bulk, and linear size goes as the cube root of
 * it. The two are blended in relativeModelScale() so neither dominates — mass
 * alone would shrink a gas Pokemon like Gastly (0.1 kg) to nothing.
 *
 * Weights come from PokeAPI in hectograms; stored in kilograms.
 *
 * Usage: node tools/fetch-weights.mjs [maxDex]
 */
import { writeFile } from "node:fs/promises";

const MAX = Number(process.argv[2] ?? 1025);
const CONC = 12;

async function weightFor(dex) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(`https://pokeapi.co/api/v2/pokemon/${dex}`);
      if (!res.ok) {
        if (res.status === 404) return null;
        throw new Error(`HTTP ${res.status}`);
      }
      const json = await res.json();
      // PokeAPI gives hectograms.
      const kg = json.weight / 10;
      return Number.isFinite(kg) && kg > 0 ? Math.round(kg * 10) / 10 : null;
    } catch {
      await new Promise((r) => setTimeout(r, 400 * (attempt + 1)));
    }
  }
  return null;
}

const targets = Array.from({ length: MAX }, (_, i) => i + 1);
const weights = new Map();

for (let i = 0; i < targets.length; i += CONC) {
  const chunk = targets.slice(i, i + CONC);
  const got = await Promise.all(chunk.map(weightFor));
  chunk.forEach((dex, k) => { if (got[k] != null) weights.set(dex, got[k]); });
  process.stderr.write(`\r  ${Math.min(i + CONC, targets.length)}/${targets.length}`);
}
process.stderr.write("\n");

const entries = [...weights.entries()].sort((a, b) => a[0] - b[0]);
const cbrts = entries.map(([, kg]) => Math.cbrt(kg)).sort((a, b) => a - b);
const medianCbrt = Math.round(cbrts[Math.floor(cbrts.length / 2)] * 1000) / 1000;

const body = entries.map(([dex, kg]) => `  ${dex}: ${kg},`).join("\n");
await writeFile(
  new URL("../src/game/data/mon-weights.ts", import.meta.url),
  `/**
 * Canonical species weight in KILOGRAMS, keyed by national dex number.
 *
 * Generated by tools/fetch-weights.mjs from PokeAPI — do not hand-edit; re-run
 * the tool instead.
 *
 * Used together with MON_HEIGHT_M to size units. Height alone measures a snake
 * along its length, so it made coiled species render far larger than they look;
 * mass carries the bulk that height misses. See relativeModelScale().
 */
export const MON_WEIGHT_KG: Readonly<Record<number, number>> = {
${body}
};

/**
 * Median of cbrt(weight) across the roster.
 *
 * The cube root because linear size goes as the cube root of mass; the median
 * so a species of typical bulk scores 1, matching REFERENCE_HEIGHT_M.
 */
export const REFERENCE_MASS_CBRT = ${medianCbrt};
`,
);

const vals = entries.map(([, kg]) => kg).sort((a, b) => a - b);
console.log(`wrote ${entries.length} weights`);
console.log(`  min ${vals[0]} kg   median ${vals[Math.floor(vals.length / 2)]} kg   max ${vals[vals.length - 1]} kg`);
console.log(`  REFERENCE_MASS_CBRT = ${medianCbrt}`);
