/**
 * Measures where the VISIBLE art actually sits inside each sprite PNG, and
 * bakes it to src/game/data/sprite-trim.ts.
 *
 * Why: every sprite is a 96x96 frame that is mostly transparent padding, and
 * the amount of padding differs wildly between species. The renderer anchors
 * things to the sprite's BOX — star badges "just above the sprite", combat HP
 * bars "above the crown" — so they land far above the actual head, by a
 * different distance for every mon. On the board that detaches a unit's stars
 * from the unit; in combat it floats the HP bar more than half a hex up, where
 * it reads as belonging to the mon in front.
 *
 * Measured with a real canvas via Playwright rather than a hand-rolled PNG
 * decoder: these are 4-bit palette PNGs with tRNS, and getting alpha right
 * across every variant is exactly the kind of thing a browser already does.
 *
 * Usage: node tools/trim-sprites.mjs [url]
 *   Needs a dev server running (it fetches /sprites/<dex>.png from it).
 */
import { chromium } from "playwright";
import { readdir, writeFile } from "node:fs/promises";

const SERVER = process.argv[2] ?? "http://localhost:3000";
const BATCH = 64;

const files = (await readdir(new URL("../public/sprites", import.meta.url)))
  .filter((f) => /^\d+\.png$/.test(f))
  .map((f) => Number(f.replace(".png", "")))
  .sort((a, b) => a - b);

console.log(`measuring ${files.length} sprites via ${SERVER}`);

const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(SERVER, { waitUntil: "domcontentloaded" });

/** Opaque bounding box, as fractions of the frame. */
const measure = async (dexes) =>
  page.evaluate(async (list) => {
    const out = {};
    const canvas = document.createElement("canvas");
    const ctx = canvas.getContext("2d", { willReadFrequently: true });
    for (const dex of list) {
      try {
        const res = await fetch(`/sprites/${dex}.png`);
        if (!res.ok) continue;
        const bitmap = await createImageBitmap(await res.blob());
        canvas.width = bitmap.width;
        canvas.height = bitmap.height;
        ctx.clearRect(0, 0, bitmap.width, bitmap.height);
        ctx.drawImage(bitmap, 0, 0);
        const { data } = ctx.getImageData(0, 0, bitmap.width, bitmap.height);
        let x0 = bitmap.width, y0 = bitmap.height, x1 = -1, y1 = -1;
        for (let y = 0; y < bitmap.height; y++) {
          for (let x = 0; x < bitmap.width; x++) {
            // 8 not 0: a few sprites carry a faint anti-aliased halo that would
            // otherwise count as "art" and undo the whole measurement.
            if (data[(y * bitmap.width + x) * 4 + 3] > 8) {
              if (x < x0) x0 = x;
              if (x > x1) x1 = x;
              if (y < y0) y0 = y;
              if (y > y1) y1 = y;
            }
          }
        }
        if (x1 < 0) continue; // fully transparent
        const r = (n) => Math.round(n * 1000) / 1000;
        out[dex] = [
          r(x0 / bitmap.width),
          r(y0 / bitmap.height),
          r((x1 + 1) / bitmap.width),
          r((y1 + 1) / bitmap.height),
        ];
        bitmap.close();
      } catch { /* skip */ }
    }
    return out;
  }, dexes);

const trim = {};
for (let i = 0; i < files.length; i += BATCH) {
  Object.assign(trim, await measure(files.slice(i, i + BATCH)));
  process.stderr.write(`\r  ${Math.min(i + BATCH, files.length)}/${files.length}`);
}
process.stderr.write("\n");
await browser.close();

const entries = Object.entries(trim).map(([d, v]) => [Number(d), v]).sort((a, b) => a[0] - b[0]);
const body = entries.map(([dex, v]) => `  ${dex}: [${v.join(", ")}],`).join("\n");

await writeFile(
  new URL("../src/game/data/sprite-trim.ts", import.meta.url),
  `/**
 * Where the visible art sits inside each sprite frame, as [x0, y0, x1, y1]
 * fractions of the 96x96 PNG.
 *
 * Generated by tools/trim-sprites.mjs — do not hand-edit; re-run the tool.
 *
 * Sprites are mostly transparent padding, and how much differs per species. Any
 * UI anchored to the sprite's BOX rather than its ART therefore lands a
 * different distance from the mon for every mon: star badges floated off the
 * top of a unit, and combat HP bars sat more than half a hex above theirs,
 * close enough to the unit in front to look like its bar. See spriteArt().
 */
export const SPRITE_TRIM: Readonly<Record<number, readonly [number, number, number, number]>> = {
${body}
};
`,
);

const tops = entries.map(([, v]) => v[1]);
const avg = tops.reduce((a, b) => a + b, 0) / tops.length;
console.log(`wrote ${entries.length} entries`);
console.log(`  top padding: min ${Math.min(...tops)}  max ${Math.max(...tops)}  mean ${avg.toFixed(3)}`);
console.log(`  (a frame with 0.3 top padding wastes ~30% of the sprite height above the mon's head)`);
