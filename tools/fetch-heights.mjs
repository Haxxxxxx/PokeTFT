/**
 * Bakes each species' canonical height into src/game/data/mon-heights.ts.
 *
 * Why this exists: UnitModel normalised EVERY model to one fixed height
 * (MODEL_TARGET_HEIGHT / boundingBox.y), which threw away relative scale
 * entirely — a Rattata and a Charizard rendered exactly the same size. That is
 * the "sizes are messed up" complaint: the small mons are not too big by a
 * tuning margin, they are drawn at the same height as everything else by
 * construction.
 *
 * Heights come from PokéAPI in decimetres; we store metres rounded to 1dp,
 * which is the precision the source actually has.
 *
 * Usage: node tools/fetch-heights.mjs [maxDex]
 */
import { writeFile } from "node:fs/promises";

const MAX = Number(process.argv[2] ?? 1025);
const CONC = 12;

async function heightFor(dex) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(`https://pokeapi.co/api/v2/pokemon/${dex}`);
      if (!res.ok) {
        if (res.status === 404) return null;
        throw new Error(`HTTP ${res.status}`);
      }
      const json = await res.json();
      // PokéAPI gives decimetres.
      const m = json.height / 10;
      return Number.isFinite(m) && m > 0 ? Math.round(m * 10) / 10 : null;
    } catch {
      await new Promise((r) => setTimeout(r, 400 * (attempt + 1)));
    }
  }
  return null;
}

const targets = Array.from({ length: MAX }, (_, i) => i + 1);
const heights = new Map();

for (let i = 0; i < targets.length; i += CONC) {
  const chunk = targets.slice(i, i + CONC);
  const got = await Promise.all(chunk.map(heightFor));
  chunk.forEach((dex, k) => { if (got[k] != null) heights.set(dex, got[k]); });
  process.stderr.write(`\r  ${Math.min(i + CONC, targets.length)}/${targets.length}`);
}
process.stderr.write("\n");

const missing = targets.filter((d) => !heights.has(d));
const entries = [...heights.entries()].sort((a, b) => a[0] - b[0]);

const body = entries.map(([dex, m]) => `  ${dex}: ${m},`).join("\n");
const out = `/**
 * Canonical species height in METRES, keyed by national dex number.
 *
 * Generated by tools/fetch-heights.mjs from PokéAPI — do not hand-edit; re-run
 * the tool instead.
 *
 * Used by UnitModel to give units RELATIVE size. Before this existed every
 * model was normalised to one fixed height, so a Rattata (0.3 m) and a
 * Charizard (1.7 m) rendered identically and the small mons read as far too
 * big. See relativeModelScale() for how these are compressed into a range
 * that stays readable on a hex.
 */
export const MON_HEIGHT_M: Readonly<Record<number, number>> = {
${body}
};

/** Median-ish reference height. A species this tall renders at scale 1. */
export const REFERENCE_HEIGHT_M = 1;
`;

await writeFile(new URL("../src/game/data/mon-heights.ts", import.meta.url), out);

const vals = entries.map(([, m]) => m).sort((a, b) => a - b);
console.log(`wrote ${entries.length} heights (${missing.length} missing)`);
console.log(`  min ${vals[0]} m   median ${vals[Math.floor(vals.length / 2)]} m   max ${vals[vals.length - 1]} m`);
if (missing.length) console.log(`  missing dex: ${missing.slice(0, 20).join(", ")}${missing.length > 20 ? "…" : ""}`);
